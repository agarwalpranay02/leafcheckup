import { chromium } from "playwright";
const base = "http://localhost:3000";
const browser = await chromium.launch({ executablePath: "/usr/bin/google-chrome", args: ["--no-sandbox"] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const p = await ctx.newPage();
const errs = []; p.on("pageerror", (e) => errs.push(e.message)); p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
await p.goto(`${base}/hi`, { waitUntil: "networkidle" });
await p.screenshot({ path: "/home/claude/shots/m-hi-1.png" });
await p.evaluate(() => window.scrollTo(0, 844)); await p.waitForTimeout(300);
await p.screenshot({ path: "/home/claude/shots/m-hi-2.png" });
await p.goto(`${base}/en/diagnose`, { waitUntil: "networkidle" });
await p.setInputFiles('input[type=file][accept^="image/jpeg"]', "public/samples/ridge_gourd__leaf_miner.jpg");
await p.waitForSelector("article h2", { timeout: 60000 });
await p.waitForTimeout(800);
await p.evaluate(() => window.scrollTo(0, 0));
await p.screenshot({ path: "/home/claude/shots/m-diag-1.png" });
await p.evaluate(() => window.scrollTo(0, document.querySelector("article").getBoundingClientRect().top + window.scrollY - 70)); await p.waitForTimeout(300);
await p.screenshot({ path: "/home/claude/shots/m-diag-2.png" });
await p.locator("header button[aria-controls=mobile-nav]").click(); await p.waitForTimeout(200);
await p.screenshot({ path: "/home/claude/shots/m-menu.png" });
console.log("errors", errs);
await browser.close();
